"""Build the browser's offline catalog from the 商品样本 worksheet."""

import argparse
import json
from pathlib import Path

from openpyxl import load_workbook


FIELDS = (
    "商品ID", "候选商品", "平台", "一级品类", "细分类目", "目标售价（元）",
    "采购单价（元）", "起订量（件）", "近30天需求变化", "同类竞品数",
    "竞品最低价（元）", "竞品最高价（元）", "好评主题", "差评主题", "拿样检查项", "数据性质",
)


def build(workbook_path):
    with workbook_path.open("rb") as stream:
        workbook = load_workbook(stream, read_only=True, data_only=True)
        try:
            rows = workbook["商品样本"].values
            header = next(rows)
            columns = [header.index(name) for name in FIELDS]
            products = []
            unique_ids = set()
            for row in rows:
                if not any(value is not None for value in row):
                    continue
                (id_, name, platform, category, kind, price, cost, moq, trend, competitors, low, high,
                 benefit, complaint, check, source) = (row[index] for index in columns)
                if not isinstance(id_, str) or not id_ or id_ in unique_ids:
                    raise ValueError(f"Invalid or duplicate product ID: {id_!r}")
                if platform != "抖音电商" or category != "桌面收纳" or source != "模拟样本":
                    raise ValueError(f"Expected a simulated Douyin desktop-organizer sample: {id_}")
                unique_ids.add(id_)
                change = round(trend * 100, 2)
                evidence = [
                    ("market", "竞品样本", f"同类商品 {competitors} 款，参考售价 ¥{low:g}–{high:g}。", "演示快照"),
                    ("trend", "趋势样本", f"近 30 天需求指标较前 30 天变化 {change:+g}%。", "模拟 30 天窗口"),
                ]
                if benefit:
                    evidence.append(("benefit", "好评主题", benefit, "样本评论归纳"))
                if complaint:
                    evidence.append(("risk", "差评主题", complaint, "样本评论归纳"))
                if cost is not None or moq is not None:
                    price_note = f"采购单价 ¥{cost:g}" if cost is not None else "采购单价待补"
                    moq_note = f"起订 {moq} 件" if moq is not None else "起订量待补"
                    evidence.append(("cost", "采购数据", f"{price_note}，{moq_note}。", "模拟供应商数据"))
                products.append({
                    "id": id_, "name": name, "type": kind, "price": price, "unitCost": cost,
                    "minimumOrder": moq, "change": change, "competitors": competitors, "check": check,
                    "evidence": [{"id": f"{id_}-{key}", "label": label, "text": value, "period": period}
                                 for key, label, value, period in evidence],
                })
            return products
        finally:
            workbook.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", type=Path)
    args = parser.parse_args()
    products = build(args.workbook)
    target = Path(__file__).resolve().parents[1] / "catalog.js"
    records = ",\n".join("  " + json.dumps(product, ensure_ascii=False, separators=(",", ":"))
                           for product in products)
    target.write_text(
        "// Generated by tools/build_catalog.py from the simulated Excel workbook.\n"
        "(function () {\nconst catalog = [\n" + records +
        "\n];\nif (typeof module === \"object\" && module.exports) module.exports = catalog;\n"
        "else window.productCatalog = catalog;\n})();\n",
        encoding="utf-8",
    )
    print(f"Built catalog with {len(products)} rows.")


if __name__ == "__main__":
    main()
